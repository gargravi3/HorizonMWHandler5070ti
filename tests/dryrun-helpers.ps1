# Runs the helper prelude of HorizonMW.js under the same Jint engine Nucleus uses,
# against a throwaway sandbox, and asserts the byte-level and text-level behaviour
# that the handler depends on. Touches nothing outside the sandbox.

$ErrorActionPreference = 'Stop'

$repo   = Split-Path -Parent $PSScriptRoot
$jint   = 'C:\NucleusCoop\Jint.dll'
$sandbox = Join-Path $env:TEMP ('hmw-dryrun-' + [Guid]::NewGuid().ToString('N').Substring(0, 8))

Add-Type -Path $jint

# Take only the helper prelude, i.e. everything before the Game definition.
$src    = [IO.File]::ReadAllText((Join-Path $repo 'HorizonMW.js'))
$marker = '// Game definition'
$cut    = $src.IndexOf($marker)
if ($cut -lt 0) { throw "marker '$marker' not found in HorizonMW.js" }
$prelude = $src.Substring(0, $cut)

New-Item -ItemType Directory -Force -Path (Join-Path $sandbox 'src\user'), (Join-Path $sandbox 'inst'), (Join-Path $sandbox 'appdata') | Out-Null

# A source install to seed from: config has a name line, no favourites.json.
$srcP2 = Join-Path $sandbox 'src'
@(
    '// generated by Call of Duty: MWR - do not modify',
    'seta cg_drawFPS "0"',
    'seta name "gargr"',
    'seta com_maxfps "0"'
) -join "`r`n" | Set-Content -LiteralPath (Join-Path $srcP2 'config_mp.cfg') -Encoding Ascii -NoNewline
'{}' | Set-Content -LiteralPath (Join-Path $srcP2 'history.json') -Encoding Ascii -NoNewline
'cdta' | Set-Content -LiteralPath (Join-Path $srcP2 'user\hmwcdta') -Encoding Ascii -NoNewline

# A pre-existing identity to be backed up and restored.
$appdata = Join-Path $sandbox 'appdata'
'REAL-GUID' | Set-Content -LiteralPath (Join-Path $appdata 'hwgd.pf') -Encoding Ascii -NoNewline
'REAL-KEY'  | Set-Content -LiteralPath (Join-Path $appdata 'hmw-key') -Encoding Ascii -NoNewline

$engine = New-Object Jint.Engine ([Action[Jint.Options]] { param($o) [void]$o.AllowClr() })
[void]$engine.Execute($prelude)

# Point the identity helpers at the sandbox instead of the real %LOCALAPPDATA%.
[void]$engine.Execute("hmwRealAppData = function () { return " + (ConvertTo-Json $appdata) + "; };")

$jsSandbox = ConvertTo-Json $sandbox
[void]$engine.Execute(@"
var SB      = $jsSandbox;
var srcP2   = SB + '\\src';
var inst    = SB + '\\inst';
var players2 = inst + '\\players2';
var users    = players2 + '\\user';

hmwEnsureDir(players2);
hmwEnsureDir(users);

hmwSeedFile(srcP2 + '\\config_mp.cfg', players2 + '\\config_mp.cfg');
hmwSeedOrCreate(srcP2 + '\\favourites.json', players2 + '\\favourites.json', '[]');
hmwSeedOrCreate(srcP2 + '\\history.json',    players2 + '\\history.json',    '[]');
hmwSeedOrCreate(srcP2 + '\\user\\hmwcdta',   users + '\\hmwcdta', '');
hmwSeedOrCreate(srcP2 + '\\user\\hmwdta',    users + '\\hmwdta',  '');

// existing dvar gets replaced, absent dvar gets appended
hmwSetCfgValue(players2 + '\\config_mp.cfg', 'seta name', 'Player2');
hmwSetCfgValue(players2 + '\\config_mp.cfg', 'seta net_dummy', '1');

// re-seeding must not clobber the edit
hmwSeedFile(srcP2 + '\\config_mp.cfg', players2 + '\\config_mp.cfg');

hmwWriteGuid(players2 + '\\hwgd.pf', '{00000000-0000-4000-8000-000000000002}');

hmwBackupIdentityOnce();
hmwWriteGuid(hmwRealAppData() + '\\hwgd.pf', '{00000000-0000-4000-8000-000000000002}');
hmwDelete(hmwRealAppData() + '\\hmw-key');
"@)

# --- assertions -------------------------------------------------------------

$fail = 0
function Check([string]$name, [scriptblock]$test) {
    $ok = $false
    try { $ok = [bool](& $test) } catch { $ok = $false }
    if ($ok) { "  PASS  $name" } else { "  FAIL  $name"; $script:fail++ }
}

$p2  = Join-Path $sandbox 'inst\players2'
$cfg = Get-Content -LiteralPath (Join-Path $p2 'config_mp.cfg')

"dry run in $sandbox"
Check 'players2 and players2\user created'      { (Test-Path (Join-Path $p2 'user')) }
Check 'config_mp.cfg seeded'                    { Test-Path (Join-Path $p2 'config_mp.cfg') }
Check 'favourites.json created as []'           { (Get-Content -LiteralPath (Join-Path $p2 'favourites.json') -Raw) -eq '[]' }
Check 'history.json seeded from install'        { (Get-Content -LiteralPath (Join-Path $p2 'history.json') -Raw) -eq '{}' }
Check 'user\hmwcdta seeded from install'        { (Get-Content -LiteralPath (Join-Path $p2 'user\hmwcdta') -Raw) -eq 'cdta' }
Check 'user\hmwdta created empty'               { (Get-Item -LiteralPath (Join-Path $p2 'user\hmwdta')).Length -eq 0 }
Check 'existing seta name replaced'             { ($cfg | Where-Object { $_ -eq 'seta name "Player2"' }).Count -eq 1 }
Check 'old seta name gone'                      { ($cfg | Where-Object { $_ -like 'seta name "gargr"*' }).Count -eq 0 }
Check 'missing dvar appended'                   { ($cfg | Where-Object { $_ -eq 'seta net_dummy "1"' }).Count -eq 1 }
Check 'other cfg lines preserved'               { ($cfg | Where-Object { $_ -eq 'seta com_maxfps "0"' }).Count -eq 1 }
Check 'reseed did not clobber the edit'         { ($cfg | Where-Object { $_ -eq 'seta name "Player2"' }).Count -eq 1 }
Check 'hwgd.pf is exactly 39 bytes'             { (Get-Item -LiteralPath (Join-Path $p2 'hwgd.pf')).Length -eq 39 }
Check 'hwgd.pf ends with a single 0x00'         {
    $b = [IO.File]::ReadAllBytes((Join-Path $p2 'hwgd.pf'))
    $b[38] -eq 0 -and $b[37] -eq [byte][char]'}'
}
Check 'hwgd.pf has no BOM'                      { ([IO.File]::ReadAllBytes((Join-Path $p2 'hwgd.pf')))[0] -eq [byte][char]'{' }
Check 'hwgd.pf backed up before overwrite'      { (Get-Content -LiteralPath (Join-Path $sandbox 'appdata\hwgd.pf.nucleus-original') -Raw) -eq 'REAL-GUID' }
Check 'hmw-key backed up before deletion'       { (Get-Content -LiteralPath (Join-Path $sandbox 'appdata\hmw-key.nucleus-original') -Raw) -eq 'REAL-KEY' }
Check 'no backup made for absent hmw-key.pub'   { -not (Test-Path (Join-Path $sandbox 'appdata\hmw-key.pub.nucleus-original')) }
Check 'guest identity was actually mutated'     {
    (Get-Item -LiteralPath (Join-Path $sandbox 'appdata\hwgd.pf')).Length -eq 39 -and
    -not (Test-Path (Join-Path $sandbox 'appdata\hmw-key'))
}

# restore, then assert the original identity is byte-identical again
[void]$engine.Execute('hmwRestoreIdentity();')
Check 'restore brings hwgd.pf back'             { (Get-Content -LiteralPath (Join-Path $sandbox 'appdata\hwgd.pf') -Raw) -eq 'REAL-GUID' }
Check 'restore brings hmw-key back'             { (Get-Content -LiteralPath (Join-Path $sandbox 'appdata\hmw-key') -Raw) -eq 'REAL-KEY' }
Check 'backups removed after restore'           { -not (Test-Path (Join-Path $sandbox 'appdata\hwgd.pf.nucleus-original')) }
[void]$engine.Execute('hmwRestoreIdentity();')
Check 'second restore is a no-op'               { (Get-Content -LiteralPath (Join-Path $sandbox 'appdata\hwgd.pf') -Raw) -eq 'REAL-GUID' }

Remove-Item -LiteralPath $sandbox -Recurse -Force -ErrorAction SilentlyContinue

if ($fail -gt 0) { "$fail check(s) failed"; exit 1 } else { 'all checks passed'; exit 0 }
